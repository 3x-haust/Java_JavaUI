package io.github._3xhaust.tools;

import java.io.File;
import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;
import java.util.stream.Collectors;

public class AssetGenerator {
    private static final String CLASS_NAME = "Assets";

    public static void generate(Class<?> mainClass) {
        String packageName = mainClass.getPackageName();
        String targetDir = "src/main/java/" + packageName.replace('.', '/');
        String ASSETS_DIR = targetDir + "/assets";
        File assetsDir = new File(ASSETS_DIR);
        if (!assetsDir.exists() || !assetsDir.isDirectory()) {
            System.out.println("Assets directory not found at '" + assetsDir.getAbsolutePath() + "'. Skipping asset class generation.");
            return;
        }
        System.out.println("Generating assets class in '" + targetDir + "'...");
        try {
            List<Path> files = Files.walk(Paths.get(ASSETS_DIR)).filter(Files::isRegularFile).collect(Collectors.toList());
            System.out.println(files);
            File targetDirFile = new File(targetDir);
            if (!targetDirFile.exists()) {
                targetDirFile.mkdirs();
            }
            try (PrintWriter writer = new PrintWriter(targetDir + "/" + CLASS_NAME + ".java", "UTF-8")) {
                writer.println("package " + packageName + ";");
                writer.println("");
                writer.println("// This file is automatically generated. Do not edit.");
                writer.println("public final class " + CLASS_NAME + " {");
                writer.println("    private " + CLASS_NAME + "() {}");
                writer.println("");
                for (Path path : files) {
                    String relativePath = assetsDir.toURI().relativize(path.toFile().toURI()).getPath();
                    String fieldName = relativePath.replace('/', '_').replaceAll("[^a-zA-Z0-9_]", "_");
                    writer.println("    public static final String " + fieldName + " = \"" + ASSETS_DIR + "/" + relativePath + "\";");
                }
                writer.println("}");
            }
        } catch (IOException e) {
            System.err.println("Error generating assets class: " + e.getMessage());
        }
    }
}